#!/usr/bin/env bash
#
# polli-sandbox-bootstrap.sh — install the g4f sandbox menu inside a Polli
# (E2B) sandbox.
#
# `sandbox-cli polli-sandbox install-menu <id>` copies the menu assets (the
# sandbox-cli, the .desktop entries, the desktop-directories, the Xfce menu
# patch and the icons) into the sandbox and runs this script there as root.
#
#   polli-sandbox-bootstrap.sh              menu assets only (terminal use)
#   polli-sandbox-bootstrap.sh --desktop    also install Xfce + TigerVNC and
#                                           start a local desktop on 127.0.0.1:5900
#
# A Polli sandbox is a headless Debian VM, so the menu's .desktop files only
# have a visible effect with --desktop. Without it, `sandbox-cli list` and the
# individual `sandbox-cli <tool>` commands still work from any ssh session.
# With --desktop, connect through the ssh tunnel printed at the end and point
# a VNC client at 127.0.0.1:5900:
#
#   ssh -L 5900:127.0.0.1:5900 <sandbox-id>.polli
#
set -euo pipefail

DESKTOP=0
for arg in "$@"; do
    case "$arg" in
        --desktop)
            DESKTOP=1 ;;
        -h|--help|help)
            sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'
            exit 0 ;;
        *)
            printf 'polli-sandbox-bootstrap: unknown option "%s"\n' "$arg" >&2
            exit 2 ;;
    esac
done

if [ "$(id -u)" -ne 0 ]; then
    printf 'polli-sandbox-bootstrap: run as root (sudo %s)\n' "$0" >&2
    exit 1
fi

export DEBIAN_FRONTEND=noninteractive

log() { printf '==> %s\n' "$*"; }

log "installing the base packages..."
apt-get update -qq
apt-get install -y -qq --no-install-recommends ca-certificates curl

# The files were unpacked by the caller. Fix up their modes and, when a desktop
# is requested, patch the stock Xfce menu so the g4f categories appear as their
# own top-level menus.
chmod 0755 /usr/local/bin/sandbox-cli 2>/dev/null || true
chmod 0755 /usr/local/bin/patch-xfce-menu.py 2>/dev/null || true
chmod 0755 /usr/local/bin/sandbox-docs /usr/local/bin/sandbox-discover \
    /usr/local/bin/start-browser 2>/dev/null || true
chmod 0644 /usr/share/applications/g4f-sandbox-*.desktop 2>/dev/null || true
chmod 0644 /usr/share/desktop-directories/g4f-sandbox-*.directory 2>/dev/null || true

if [ "$DESKTOP" = 0 ]; then
    log "the sandbox menu is installed; run 'sandbox-cli list' in the sandbox"
    exit 0
fi

log "installing the Xfce + TigerVNC desktop..."
apt-get install -y -qq --no-install-recommends \
    xfce4-panel xfwm4 xfdesktop4 xfce4-settings xfce4-terminal \
    dbus-x11 x11-xserver-utils x11-xkb-utils tigervnc-standalone-server \
    fonts-dejavu-core fonts-noto-core fonts-noto-color-emoji \
    librsvg2-common adwaita-icon-theme gtk-update-icon-cache \
    procps

if [ -f /etc/xdg/menus/xfce-applications.menu ]; then
    /usr/local/bin/patch-xfce-menu.py
else
    log "warning: /etc/xdg/menus/xfce-applications.menu is missing; entries stay in the Other menu"
fi

if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -f -t /usr/share/icons/hicolor >/dev/null 2>&1 || true
fi

# Start Xvnc and the Xfce components the menu needs, as the sandbox's
# unprivileged user. The desktop listens on loopback only; reach it through an
# ssh tunnel (Polli's port forwarding) rather than exposing 5900 publicly.
cat > /usr/local/bin/g4f-sandbox-desktop <<'LAUNCHER'
#!/bin/sh
# Generated by polli-sandbox-bootstrap.sh --desktop.
set -eu

display="${G4F_SANDBOX_DISPLAY:-:1}"
port="${G4F_SANDBOX_VNC_PORT:-5900}"
geometry="${G4F_SANDBOX_GEOMETRY:-1280x800}"
runtime="${XDG_RUNTIME_DIR:-/tmp/g4f-sandbox-runtime}"

mkdir -p "$runtime"
chmod 700 "$runtime" 2>/dev/null || true
export DISPLAY="$display"
export XDG_RUNTIME_DIR="$runtime"

num="${display#:}"
lock="/tmp/.X${num}-lock"
if [ -e "$lock" ]; then
    pid="$(tr -d ' \n' < "$lock" 2>/dev/null || true)"
    if [ -z "$pid" ] || ! tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null | grep -q Xvnc; then
        rm -f "$lock" "/tmp/.X11-unix/X${num}"
    fi
fi

nohup Xvnc "$display" -rfbport "$port" -localhost \
    -SecurityTypes None -geometry "$geometry" -depth 24 -nolisten tcp \
    >/tmp/g4f-sandbox-xvnc.log 2>&1 &
for _ in $(seq 1 50); do
    [ -S "/tmp/.X11-unix/X${num}" ] && break
    sleep 0.2
done

nohup xfsettingsd >/tmp/g4f-sandbox-xfsettingsd.log 2>&1 &
nohup xfwm4 >/tmp/g4f-sandbox-xfwm4.log 2>&1 &
nohup xfce4-panel >/tmp/g4f-sandbox-panel.log 2>&1 &
nohup xfdesktop >/tmp/g4f-sandbox-xfdesktop.log 2>&1 &

printf 'Xfce is running on display %s; VNC is listening on 127.0.0.1:%s\n' \
    "$display" "$port"
LAUNCHER
chmod 0755 /usr/local/bin/g4f-sandbox-desktop

user_name="${POLLI_USER:-user}"
if ! id "$user_name" >/dev/null 2>&1; then
    user_name="$(getent passwd | awk -F: '$3 >= 1000 && $3 < 60000 { print $1; exit }')"
fi
[ -n "$user_name" ] || user_name="root"
user_home="$(getent passwd "$user_name" | cut -d: -f6)"
runtime="/tmp/g4f-sandbox-runtime"
install -d -m 700 -o "$user_name" -g "$(id -gn "$user_name")" "$runtime" 2>/dev/null || true

log "starting the desktop as $user_name..."
runuser -u "$user_name" -- env HOME="$user_home" XDG_RUNTIME_DIR="$runtime" \
    setsid /usr/local/bin/g4f-sandbox-desktop \
    >/tmp/g4f-sandbox-desktop.log 2>&1 </dev/null &

sleep 2
cat <<EOF

The g4f sandbox menu is installed in this Polli sandbox.

Open an ssh tunnel from your machine (replace <id> with this sandbox's id):

    ssh -L 5900:127.0.0.1:5900 <id>.polli

Then point a VNC client at 127.0.0.1:5900. The Applications menu carries the
g4f menus (Media > Polli, Coding Agents, ...). For terminal-only use without
the desktop, run `sandbox-cli list` in the sandbox.
EOF
