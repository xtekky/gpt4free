"""The `sandbox-cli list` inventory consumed by the Android app store.

`list` appends a `g4f-bin commands` group read from the container at runtime,
so the store can show every bundled command without an APK update.
"""

import os
import subprocess
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CLI = REPO / "bin" / "sandbox-cli"
COPIES = (
    REPO / "projects/android/app/src/main/assets/container/bin/sandbox-cli",
    REPO / "g4f-go/polli/assets/sandbox-cli",
)


def read_listing(bin_dir):
    """Run the real CLI with an isolated HOME and return stdout."""
    with tempfile.TemporaryDirectory() as home:
        env = dict(os.environ)
        env.update(HOME=home, SANDBOX_SYSTEM_BIN_DIR=str(Path(home) / "bin"),
                   G4F_BIN_DIR=str(bin_dir))
        result = subprocess.run(["bash", str(CLI), "list"], env=env,
                                capture_output=True, text=True, check=True,
                                timeout=30)
    return result.stdout


def parse_groups(output):
    """Mirror StoreView.parse(): unindented headers, indented entries."""
    groups = {}
    group = None
    for line in output.splitlines():
        if not line.strip():
            continue
        if not line.startswith(" "):
            group = line.strip()
            groups.setdefault(group, [])
        elif group:
            parts = line.strip().split(None, 1)
            if len(parts) == 2:
                groups[group].append((parts[0], parts[1]))
    return groups


class SandboxCliBinCatalogTests(unittest.TestCase):
    def test_list_appends_all_bin_commands_with_descriptions(self):
        with tempfile.TemporaryDirectory() as tmp:
            bin_dir = Path(tmp) / "bin"
            bin_dir.mkdir()
            (bin_dir / "hello").write_text(
                "#!/bin/sh\n# Say hello from the test\necho hello\n", encoding="utf-8")
            (bin_dir / "notes.py").write_text(
                "#!/usr/bin/env python3\n\"\"\"Show notes.\"\"\"\n", encoding="utf-8")
            (bin_dir / "plain.sh").write_text("#!/bin/sh\necho plain\n", encoding="utf-8")
            (bin_dir / "blob").write_bytes(b"\x7fELF not a script\n")
            (bin_dir / "subdir").mkdir()
            groups = parse_groups(read_listing(bin_dir))

        self.assertIn("g4f-bin commands", groups)
        entries = dict(groups["g4f-bin commands"])
        self.assertEqual(set(entries), {"hello", "notes.py", "plain.sh", "blob"})
        self.assertEqual(entries["hello"], "Say hello from the test")
        self.assertEqual(entries["notes.py"], "Show notes.")
        self.assertEqual(entries["plain.sh"], "command from /g4f-bin")
        self.assertEqual(entries["blob"], "command from /g4f-bin")

    def test_every_repository_bin_command_is_listed(self):
        expected = {path.name for path in (REPO / "bin").iterdir() if path.is_file()}
        groups = parse_groups(read_listing(REPO / "bin"))
        listed = {name for name, _ in groups.get("g4f-bin commands", [])}
        self.assertTrue(expected)
        self.assertEqual(listed, expected)

    def test_generated_copies_match_the_source(self):
        source = CLI.read_bytes()
        for copy in COPIES:
            with self.subTest(copy=copy):
                if not copy.exists():
                    # g4f-go/polli/assets is generated by sync-assets.sh.
                    raise unittest.SkipTest("generated copy is not present")
                self.assertEqual(copy.read_bytes(), source)


if __name__ == "__main__":
    unittest.main()
